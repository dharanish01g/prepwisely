/** A random password from PASSWORD_CHARS (rejection sampling, so every character is equally likely). */
function generatePassword(): string {
  const out: string[] = [];
  const limit = 256 - (256 % PASSWORD_CHARS.length);
  while (out.length < GENERATED_PASSWORD_LENGTH) {
    for (const byte of crypto.getRandomValues(new Uint8Array(32))) {
      if (byte < limit && out.length < GENERATED_PASSWORD_LENGTH) out.push(PASSWORD_CHARS[byte % PASSWORD_CHARS.length]);
    }
  }
  return out.join("");
}

function passwordProblem(password: string): string | null {
  if (password.length < MIN_PASSWORD_LENGTH) return `Password must be at least ${MIN_PASSWORD_LENGTH} characters`;
  if (password.length > MAX_PASSWORD_LENGTH) return `Password can be at most ${MAX_PASSWORD_LENGTH} characters`;
  return null;
}

/** An optional id from the request: undefined/null/"" mean none. */
const optionalId = (v: unknown) => (typeof v === "string" && v.trim() ? v.trim() : null);

/** Looks up the college and checks the caller may manage it. */
async function loadCollege(admin: Admin, caller: Caller, collegeId: string) {
  if (!collegeId) return { error: fail(400, "college_id is required") };
  if (!UUID_RE.test(collegeId)) return { error: fail(404, "College not found") };
  const { data, error } = await admin.from("colleges").select("id").eq("id", collegeId).maybeSingle();
  if (error) return { error: fail(500, "Could not load college") };
  if (!data || !(await canManageCollege(caller, data.id as string))) return { error: fail(404, "College not found") };
  return { college: { id: data.id as string } };
}

/** Looks up the faculty member and checks the caller may manage them. */
async function loadFaculty(admin: Admin, caller: Caller, facultyId: string) {
  if (!facultyId) return { error: fail(400, "faculty_id is required") };
  if (!UUID_RE.test(facultyId)) return { error: fail(404, "Faculty not found") };
  const { data, error } = await admin.from("faculty").select("id, college_id, status").eq("id", facultyId).maybeSingle();
  if (error) return { error: fail(500, "Could not load faculty") };
  if (!data || !(await canManageCollege(caller, data.college_id as string))) return { error: fail(404, "Faculty not found") };
  return { faculty: { id: data.id as string, college_id: data.college_id as string, status: data.status as string } };
}

interface FacultyInput {
  row: number;
  full_name: string;
  email: string;
  phone: string;
  department_id: string | null;
  faculty_role_id: string | null;
}

function validateFaculty(f: FacultyInput): string[] {
  const problems: string[] = [];
  if (!f.full_name) problems.push("Full name is required");
  if (!EMAIL_RE.test(f.email)) problems.push("A valid email is required");
  return problems;
}

/** Readable messages for the errors the faculty database functions raise on purpose; anything else stays generic. */
function facultyDbError(message: string, fallback: string): string {
  if (message.includes("faculty_email_key")) return "A user with this email already exists";
  if (message === "Department not found") return "Department not found in this college";
  if (message === "Faculty role not found") return "Current role not found";
  if (message === "College not found" || message === "Faculty not found") return message;
  return fallback;
}

/** Creates the auth user and the faculty row; removes the auth user again if the row can't be written. */
async function createFacultyAccount(
  admin: Admin,
  callerId: string,
  collegeId: string,
  f: FacultyInput,
  password: string,
): Promise<{ id?: string; code?: string; error?: string }> {
  const { data: created, error: createError } = await admin.auth.admin.createUser({
    email: f.email,
    password,
    email_confirm: true,
  });
  if (createError || !created.user) {
    const exists = createError?.code === "email_exists" || /already/i.test(createError?.message ?? "");
    return { error: exists ? "A user with this email already exists" : (createError?.message ?? "Could not create account") };
  }
  const { data: code, error: rowError } = await admin.rpc("college_create_faculty", {
    p_id: created.user.id,
    p_college_id: collegeId,
    p_full_name: f.full_name,
    p_email: f.email,
    p_phone: f.phone,
    p_department_id: f.department_id,
    p_faculty_role_id: f.faculty_role_id,
    p_created_by: callerId,
  });
  if (rowError) {
    await admin.auth.admin.deleteUser(created.user.id);
    return { error: facultyDbError(rowError.message, "Could not create faculty") };
  }
  return { id: created.user.id, code: code as string };
}

async function createFaculty(admin: Admin, caller: Caller, body: Record<string, unknown>) {
  const loaded = await loadCollege(admin, caller, str(body.college_id));
  if (loaded.error) return loaded.error;
  const faculty: FacultyInput = {
    row: 1,
    full_name: str(body.full_name),
    email: str(body.email).toLowerCase(),
    phone: str(body.phone),
    department_id: optionalId(body.department_id),
    faculty_role_id: optionalId(body.faculty_role_id),
  };
  const problems = validateFaculty(faculty);
  if (faculty.department_id && !UUID_RE.test(faculty.department_id)) problems.push("Department not found in this college");
  const password = typeof body.password === "string" ? body.password : "";
  const badPassword = passwordProblem(password);
  if (badPassword) problems.push(badPassword);
  if (problems.length) return fail(400, problems[0]);

  try {
    if ((await emailsInUse(admin, [faculty.email])).has(faculty.email)) return fail(409, "A user with this email already exists");
  } catch (e) {
    return fail(500, (e as Error).message);
  }

  const result = await createFacultyAccount(admin, caller.id, loaded.college.id, faculty, password);
  if (result.error) return fail(result.error.startsWith("A user") ? 409 : 400, result.error);
  return json({ id: result.id, code: result.code }, 201);
}

// All or nothing, like the student import. Department and role come as a department code and a role name (or id),
// matched against the college's departments and the faculty role list. Every account gets a generated password,
// returned once in the response for the manager to hand out.
async function importFaculty(admin: Admin, caller: Caller, body: Record<string, unknown>) {
  const loaded = await loadCollege(admin, caller, str(body.college_id));
  if (loaded.error) return loaded.error;
  const collegeId = loaded.college.id;
  if (!Array.isArray(body.faculty) || body.faculty.length === 0) return fail(400, "No faculty to import");
  if (body.faculty.length > MAX_IMPORT_ROWS) return fail(400, `At most ${MAX_IMPORT_ROWS} faculty per import`);

  const [departments, roles] = await Promise.all([
    admin.from("departments").select("id, code").eq("college_id", collegeId).is("archived_at", null),
    admin.from("faculty_roles").select("id, label").eq("is_active", true),
  ]);
  if (departments.error || roles.error) return fail(500, "Could not load departments and roles");
  const departmentByCode = new Map(departments.data.map((d) => [(d.code as string).toUpperCase(), d.id as string]));
  const roleByName = new Map<string, string>();
  for (const r of roles.data) {
    roleByName.set((r.id as string).toLowerCase(), r.id as string);
    roleByName.set((r.label as string).trim().toLowerCase(), r.id as string);
  }

  const errors: { row: number; message: string }[] = [];
  const rows = (body.faculty as Record<string, unknown>[]).map((raw, i) => {
    raw = raw ?? {};
    const row = typeof raw.row === "number" ? raw.row : i + 2;
    const departmentCode = str(raw.department_code).toUpperCase();
    const roleName = str(raw.faculty_role).toLowerCase();
    const f: FacultyInput = {
      row,
      full_name: str(raw.full_name),
      email: str(raw.email).toLowerCase(),
      phone: str(raw.phone),
      department_id: departmentCode ? (departmentByCode.get(departmentCode) ?? null) : null,
      faculty_role_id: roleName ? (roleByName.get(roleName) ?? null) : null,
    };
    const problems = validateFaculty(f);
    if (departmentCode && !f.department_id) problems.push(`Department "${str(raw.department_code)}" not found in this college`);
    if (roleName && !f.faculty_role_id) problems.push(`Current role "${str(raw.faculty_role)}" not found`);
    for (const message of problems) errors.push({ row, message });
    return f;
  });

  let used: Set<string>;
  try {
    used = await emailsInUse(admin, rows.map((f) => f.email).filter(Boolean));
  } catch (e) {
    return fail(500, (e as Error).message);
  }
  const seenEmails = new Map<string, number>();
  for (const f of rows) {
    if (!f.email) continue;
    if (seenEmails.has(f.email)) errors.push({ row: f.row, message: `Same email as row ${seenEmails.get(f.email)}` });
    else if (used.has(f.email)) errors.push({ row: f.row, message: "A user with this email already exists" });
    if (!seenEmails.has(f.email)) seenEmails.set(f.email, f.row);
  }
  if (errors.length) {
    errors.sort((a, b) => a.row - b.row);
    return json({ error: "Fix the rows below and import again. Nothing was imported.", errors }, 400);
  }

  const accounts: { row: number; full_name: string; email: string; code: string; password: string }[] = [];
  const createdIds: string[] = [];
  for (let i = 0; i < rows.length; i += CREATE_CONCURRENCY) {
    const chunk = rows.slice(i, i + CREATE_CONCURRENCY);
    const passwords = chunk.map(() => generatePassword());
    const results = await Promise.all(chunk.map((f, j) => createFacultyAccount(admin, caller.id, collegeId, f, passwords[j])));
    results.forEach((r, j) => {
      if (!r.id) return;
      createdIds.push(r.id);
      accounts.push({ row: chunk[j].row, full_name: chunk[j].full_name, email: chunk[j].email, code: r.code!, password: passwords[j] });
    });
    const failedAt = results.findIndex((r) => r.error);
    if (failedAt !== -1) {
      await removeFacultyAccounts(admin, createdIds);
      return json(
        {
          error: "Import stopped and was undone. Nothing was imported.",
          errors: [{ row: chunk[failedAt].row, message: results[failedAt].error! }],
        },
        409,
      );
    }
  }
  return json({ created: accounts.length, accounts }, 201);
}

/** Undo for a failed import only: removes accounts this request just created (they have no assignments yet). */
async function removeFacultyAccounts(admin: Admin, ids: string[]) {
  if (!ids.length) return;
  await admin.from("faculty").delete().in("id", ids);
  await Promise.all(ids.map((id) => admin.auth.admin.deleteUser(id)));
}

