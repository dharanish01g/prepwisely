/** Looks up the TPO and checks the caller may manage them. */
async function loadTpo(admin: Admin, caller: Caller, tpoId: string) {
  if (!tpoId) return { error: fail(400, "tpo_id is required") };
  if (!UUID_RE.test(tpoId)) return { error: fail(404, "TPO not found") };
  const { data, error } = await admin.from("tpo").select("id, college_id, status").eq("id", tpoId).maybeSingle();
  if (error) return { error: fail(500, "Could not load TPO") };
  if (!data || !(await canManageCollege(caller, data.college_id as string))) return { error: fail(404, "TPO not found") };
  return { tpo: { id: data.id as string, college_id: data.college_id as string, status: data.status as string } };
}

/** Readable messages for the errors the TPO database functions raise on purpose; anything else stays generic. */
function tpoDbError(message: string, fallback: string): string {
  if (message.includes("tpo_email_key")) return "A user with this email already exists";
  if (message.includes("tpo_pkey") || message === "Already a TPO") return "This faculty member is already a TPO";
  if (message === "Designation not found") return message;
  if (message === "Faculty is inactive") return "This faculty member is inactive. Reactivate them first.";
  if (message === "College not found" || message === "Faculty not found" || message === "TPO not found") return message;
  return fallback;
}

async function createTpo(admin: Admin, caller: Caller, body: Record<string, unknown>) {
  const loaded = await loadCollege(admin, caller, str(body.college_id));
  if (loaded.error) return loaded.error;
  const fullName = str(body.full_name);
  const email = str(body.email).toLowerCase();
  const problems: string[] = [];
  if (!fullName) problems.push("Full name is required");
  if (!EMAIL_RE.test(email)) problems.push("A valid email is required");
  const password = typeof body.password === "string" ? body.password : "";
  const badPassword = passwordProblem(password);
  if (badPassword) problems.push(badPassword);
  if (problems.length) return fail(400, problems[0]);

  try {
    if ((await emailsInUse(admin, [email])).has(email)) return fail(409, "A user with this email already exists");
  } catch (e) {
    return fail(500, (e as Error).message);
  }

  const { data: created, error: createError } = await admin.auth.admin.createUser({ email, password, email_confirm: true });
  if (createError || !created.user) {
    const exists = createError?.code === "email_exists" || /already/i.test(createError?.message ?? "");
    return fail(exists ? 409 : 400, exists ? "A user with this email already exists" : (createError?.message ?? "Could not create account"));
  }
  const { data: code, error: rowError } = await admin.rpc("college_create_tpo", {
    p_id: created.user.id,
    p_college_id: loaded.college.id,
    p_full_name: fullName,
    p_email: email,
    p_phone: str(body.phone),
    p_designation_id: optionalId(body.designation_id),
    p_created_by: caller.id,
  });
  if (rowError) {
    await admin.auth.admin.deleteUser(created.user.id);
    const message = tpoDbError(rowError.message, "Could not create TPO");
    return fail(message.startsWith("A user") ? 409 : 400, message);
  }
  return json({ id: created.user.id, code }, 201);
}

