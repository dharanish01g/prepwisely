// Messages college_assign_faculty_batches / college_unassign_faculty_batch raise on purpose (safe to show as-is).
const ASSIGNMENT_ERRORS = [
  /^Faculty is inactive$/,
  /^No batches to assign$/,
  /^A batch is listed more than once$/,
  /^Batch not found$/,
  /^Archived batch: /,
  /^Already assigned: /,
  /^Assignment not found$/,
];

async function assignBatches(admin: Admin, caller: Caller, body: Record<string, unknown>) {
  const loaded = await loadFaculty(admin, caller, str(body.faculty_id));
  if (loaded.error) return loaded.error;
  if (!Array.isArray(body.batch_ids) || body.batch_ids.length === 0) return fail(400, "No batches to assign");
  const batchIds = body.batch_ids.map(str);
  if (batchIds.some((id) => !UUID_RE.test(id))) return fail(400, "Batch not found");

  const { data, error } = await admin.rpc("college_assign_faculty_batches", {
    p_faculty_id: loaded.faculty.id,
    p_batch_ids: batchIds,
    p_assigned_by: caller.id,
  });
  if (error) {
    const known = ASSIGNMENT_ERRORS.some((re) => re.test(error.message));
    return fail(known ? 400 : 500, known ? error.message : "Could not assign batches");
  }
  return json({ assigned: data }, 201);
}

async function unassignBatch(admin: Admin, caller: Caller, body: Record<string, unknown>) {
  const loaded = await loadFaculty(admin, caller, str(body.faculty_id));
  if (loaded.error) return loaded.error;
  const batchId = str(body.batch_id);
  if (!UUID_RE.test(batchId)) return fail(404, "Assignment not found");

  const { error } = await admin.rpc("college_unassign_faculty_batch", {
    p_faculty_id: loaded.faculty.id,
    p_batch_id: batchId,
    p_unassigned_by: caller.id,
  });
  if (error) {
    if (error.message === "Assignment not found") return fail(404, error.message);
    return fail(500, "Could not unassign batch");
  }
  return json({ ok: true });
}

